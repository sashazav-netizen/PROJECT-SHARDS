/* =========================================================
   עזר
========================================================= */

function קבלגודלמפה() {

    return מפה_ראשית.length;

}


function קבלנקודהלפיאינדקס(
    אינדקס
) {

    if (
        אינדקס < 0 ||
        אינדקס >= מפה_ראשית.length
    ) {

        return null;

    }


    return מפה_ראשית[
        אינדקס
    ];

}


/* =========================================================
   אייקון לפי סוג נקודה
========================================================= */

function אייקוןלסוגנקודה(
    סוג
) {

    switch (סוג) {

        case סוגי_נקודות.BATTLE:
            return "⚔️";

        case סוגי_נקודות.JOURNEY:
            return "🧭";

        case סוגי_נקודות.SHOP:
            return "🏪";

        case סוגי_נקודות.BOSS:
            return "👑";

        default:
            return "❔";

    }

}


