/* =========================================================
   עזר: יצירת עותק תבנית חפץ
========================================================= */

function צורעותקחפץ(
    מפתח
) {

    const תבנית =
        נתוני_חפצים[
            מפתח
        ];


    if (
        !תבנית
    ) {

        console.error(

            `[Item Data] לא נמצא חפץ: ${מפתח}`

        );

        return null;

    }


    try {

        return structuredClone(
            תבנית
        );

    } catch (שגיאה) {

        console.error(

            "[Item Data] שגיאה ביצירת עותק חפץ:",

            שגיאה

        );

        return null;

    }

}


