import {

    נתוני_חפצים,

    קבלכלמפתחותהחפצים

} from "../items/item-data.js";


import {

    הוסףחפץ

} from "../items/item-system.js";


import {

    קבלמצב,

    שנהמשאב

} from "../core/state.js";


import {

    פרסם

} from "../core/events.js";


/* =========================================================
   קבלת מלאי החנות
========================================================= */

/**
 * בשלב זה החנות מציעה את כל תבניות החפצים הקיימות.
 * בעתיד ניתן להחליף בקלות לרוטציה יומית/מוגבלת.
 */

function קבלמלאיחנות() {

    return קבלכלמפתחותהחפצים()

        .map(

            מפתח => ({

                מפתח,

                ...נתוני_חפצים[מפתח]

            })

        );

}


/* =========================================================
   קנייה
========================================================= */

function קנהחפץ(
    מפתח
) {

    const תבנית =
        נתוני_חפצים[
            מפתח
        ];


    if (
        !תבנית
    ) {

        console.error(

            `[Shop System] חפץ לא קיים בחנות: ${מפתח}`

        );

        return {

            הצלחה: false,

            סיבה:
                "החפץ לא קיים."

        };

    }


    const מצב =
        קבלמצב();


    const מחיר =
        תבנית.מחיר || {
            כסף: 0,
            יהלומים: 0
        };


    if (
        (מצב.שחקן.כסף || 0) < (מחיר.כסף || 0)
    ) {

        return {

            הצלחה: false,

            סיבה:
                "אין מספיק כסף."

        };

    }


    if (
        (מצב.שחקן.יהלומים || 0) < (מחיר.יהלומים || 0)
    ) {

        return {

            הצלחה: false,

            סיבה:
                "אין מספיק יהלומים."

        };

    }


    if (
        מחיר.כסף > 0
    ) {

        שנהמשאב(
            "כסף",
            -מחיר.כסף
        );

    }


    if (
        מחיר.יהלומים > 0
    ) {

        שנהמשאב(
            "יהלומים",
            -מחיר.יהלומים
        );

    }


    const instanceId =
        הוסףחפץ(
            מפתח
        );


    פרסם(

        "חפץ_נקנה",

        {

            מפתח,

            instanceId,

            מחיר

        }

    );


    return {

        הצלחה: true,

        instanceId

    };

}


/* =========================================================
   Export
========================================================= */

export {

    קבלמלאיחנות,

    קנהחפץ

};
