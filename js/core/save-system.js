/* =========================================================
   הגדרות
========================================================= */

const מפתח_שמירה =
    "project_shards_save_v1";


const גרסת_שמירה =
    "1.0.0";


/* =========================================================
   בדיקת זמינות Storage
========================================================= */

/**
 * בודק האם localStorage זמין.
 *
 * בחלק מסביבות הפיתוח או הדפדפנים
 * Storage עלול להיות חסום.
 */

function storage_זמין() {

    try {

        const מפתח_בדיקה =
            "__project_shards_test__";


        localStorage.setItem(
            מפתח_בדיקה,
            "ok"
        );


        localStorage.removeItem(
            מפתח_בדיקה
        );


        return true;

    } catch (שגיאה) {

        console.warn(
            "[Save System] LocalStorage אינו זמין.",
            שגיאה
        );


        return false;

    }

}


/* =========================================================
   יצירת Snapshot
========================================================= */

/**
 * יוצר עותק עצמאי של מצב שהועבר אליו,
 * לפני שמירתו.
 *
 * חשוב:
 * אנחנו לא שומרים את האובייקט החי
 * ישירות.
 */

function צורSnapshot(
    מצב
) {

    if (
        !מצב
    ) {

        return null;

    }


    try {

        return structuredClone(
            מצב
        );

    } catch (שגיאה) {

        console.error(
            "[Save System] לא ניתן ליצור Snapshot.",
            שגיאה
        );


        return null;

    }

}


/* =========================================================
   שמירת משחק
========================================================= */

/**
 * שומר snapshot של מצב משחק ל-localStorage.
 *
 * @param {object} מצב - מצב המשחק המלא (מ-state.js).
 * @returns {boolean}
 */

function שמורמשחק(
    מצב
) {

    if (
        !storage_זמין()
    ) {

        return false;

    }


    if (
        !מצב
    ) {

        console.warn(
            "[Save System] לא התקבל מצב משחק לשמירה."
        );


        return false;

    }


    const snapshot =
        צורSnapshot(
            מצב
        );


    if (
        !snapshot
    ) {

        return false;

    }


    const נתוני_שמירה = {

        גרסה:
            snapshot.גרסה,

        גרסת_שמירה:
            גרסת_שמירה,

        זמן_שמירה:
            Date.now(),


        פרופיל:
            snapshot.פרופיל,

        שחקן:
            snapshot.שחקן,

        התקדמות:
            snapshot.התקדמות,

        גיבורים:
            snapshot.גיבורים,

        קבוצת_גיבורים:
            snapshot.קבוצת_גיבורים,

        קלפים:
            snapshot.קלפים,

        חפצים:
            snapshot.חפצים,

        סקילים:
            snapshot.סקילים,

        חפיסה:
            snapshot.חפיסה,

        הישגים:
            snapshot.הישגים,

        משימות:
            snapshot.משימות,

        הגדרות:
            snapshot.הגדרות

    };


    try {

        localStorage.setItem(

            מפתח_שמירה,

            JSON.stringify(
                נתוני_שמירה
            )

        );


        console.log(
            "[Save System] המשחק נשמר בהצלחה."
        );


        return true;

    } catch (שגיאה) {

        console.error(
            "[Save System] שגיאה בשמירת המשחק.",
            שגיאה
        );


        return false;

    }

}


/* =========================================================
   בדיקת שמירה
========================================================= */

/**
 * בודק האם קיימת שמירה תקינה בסיסית
 * (יש נתונים ופרופיל פעיל).
 */

function יששמירה() {

    if (
        !storage_זמין()
    ) {

        return false;

    }


    try {

        const נתוניםגולמיים =
            localStorage.getItem(
                מפתח_שמירה
            );


        if (
            !נתוניםגולמיים
        ) {

            return false;

        }


        const שמירה =
            JSON.parse(
                נתוניםגולמיים
            );


        return !!(

            שמירה &&
            typeof שמירה === "object" &&
            שמירה.פרופיל &&
            שמירה.פרופיל.קיים === true

        );

    } catch (שגיאה) {

        console.error(
            "[Save System] שגיאה בבדיקת שמירה.",
            שגיאה
        );


        return false;

    }

}


/* =========================================================
   טעינת משחק
========================================================= */

/**
 * מחזיר את נתוני השמירה הגולמיים, כפי שנשמרו.
 *
 * המודול הזה אינו נוגע ב-state.js.
 * state.js הוא זה שאחראי להטמיע את הנתונים
 * חזרה למצב החי שלו.
 *
 * @returns {object|null}
 */

function טעןמשחק() {

    if (
        !storage_זמין()
    ) {

        return null;

    }


    try {

        const נתוניםגולמיים =
            localStorage.getItem(
                מפתח_שמירה
            );


        if (
            !נתוניםגולמיים
        ) {

            return null;

        }


        const שמירה =
            JSON.parse(
                נתוניםגולמיים
            );


        if (
            !שמירה ||
            typeof שמירה !== "object"
        ) {

            console.error(
                "[Save System] נתוני השמירה אינם תקינים."
            );


            return null;

        }


        console.log(
            "[Save System] המשחק נטען בהצלחה."
        );


        return שמירה;

    } catch (שגיאה) {

        console.error(
            "[Save System] שגיאה בטעינת המשחק.",
            שגיאה
        );


        return null;

    }

}


/* =========================================================
   מחיקת שמירה
========================================================= */

function מחקשמירה() {

    if (
        !storage_זמין()
    ) {

        return false;

    }


    try {

        localStorage.removeItem(
            מפתח_שמירה
        );


        console.log(
            "[Save System] השמירה נמחקה."
        );


        return true;

    } catch (שגיאה) {

        console.error(
            "[Save System] שגיאה במחיקת השמירה.",
            שגיאה
        );


        return false;

    }

}


/* =========================================================
   קבלת מידע בסיסי על השמירה
========================================================= */

/**
 * שימושי עבור מסך:
 *
 * "המשך משחק"
 *
 * כדי שנוכל להציג:
 *
 * שם שחקן
 * רמה
 * אזור
 * זמן שמירה
 * בלי לטעון את כל המצב לזיכרון החי.
 */

function קבלמידעשמירה() {

    const שמירה =
        טעןמשחק();


    if (
        !שמירה
    ) {

        return null;

    }


    return {

        גרסת_שמירה:
            שמירה.גרסת_שמירה || גרסת_שמירה,

        זמן_שמירה:
            שמירה.זמן_שמירה || null,

        שם:
            שמירה.פרופיל?.שם
            || שמירה.שחקן?.שם
            || "נוסע",

        רמה:
            שמירה.שחקן?.רמה || 1,

        אזור:
            שמירה.התקדמות?.אזור_נוכחי || 0,

        שלב:
            שמירה.התקדמות?.שלב_נוכחי || 0,

        תאריך_יצירה:
            שמירה.פרופיל?.תאריך_יצירה || null,

        תאריך_שמירה_אחרונה:
            שמירה.פרופיל?.תאריך_שמירה_אחרונה || null

    };

}


