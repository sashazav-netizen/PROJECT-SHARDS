/* =========================================================
   DOM
========================================================= */

const DOM = {

    modal:
        document.getElementById(
            "confirm-modal"
        ),

    title:
        document.getElementById(
            "confirm-modal-title"
        ),

    message:
        document.getElementById(
            "confirm-modal-message"
        ),

    yesButton:
        document.getElementById(
            "confirm-modal-yes"
        ),

    noButton:
        document.getElementById(
            "confirm-modal-no"
        )

};


/* =========================================================
   מצב פנימי
========================================================= */

let קריאתחזרהנוכחית =
    null;


/* =========================================================
   פתיחה / סגירה
========================================================= */

function פתח() {

    if (
        !DOM.modal
    ) {

        return;

    }


    DOM.modal.classList.remove(
        "hidden"
    );

    DOM.modal.setAttribute(
        "aria-hidden",
        "false"
    );

}


function סגור() {

    if (
        !DOM.modal
    ) {

        return;

    }


    DOM.modal.classList.add(
        "hidden"
    );

    DOM.modal.setAttribute(
        "aria-hidden",
        "true"
    );

}


/* =========================================================
   בקשת אישור
========================================================= */

/**
 * פותח את מודל האישור עם הטקסטים שהתבקשו.
 * onתוצאה נקראת עם true (אושר) או false (בוטל).
 */

function בקשאישור(
    אפשרויות,
    onתוצאה
) {

    if (
        !DOM.modal
    ) {

        /*
         * אם המודל לא נטען מסיבה כלשהי — לא חוסמים
         * את הפעולה, רק מדלגים על האישור.
         */

        if (
            onתוצאה
        ) {

            onתוצאה(true);

        }

        return;

    }


    קריאתחזרהנוכחית =
        onתוצאה;


    if (
        DOM.title
    ) {

        DOM.title.textContent =

            אפשרויות?.כותרת || "בטוח?";

    }


    if (
        DOM.message
    ) {

        DOM.message.textContent =

            אפשרויות?.הודעה || "";

    }


    if (
        DOM.yesButton
    ) {

        DOM.yesButton.textContent =

            אפשרויות?.טקסטאישור || "אישור";

    }


    if (
        DOM.noButton
    ) {

        DOM.noButton.textContent =

            אפשרויות?.טקסטביטול || "ביטול";

    }


    פתח();

}


/* =========================================================
   אתחול — נרשם פעם אחת בלבד
========================================================= */

function אתחלמודלאישור() {

    if (
        DOM.yesButton
    ) {

        DOM.yesButton.addEventListener(

            "click",

            () => {

                const קריאה =
                    קריאתחזרהנוכחית;


                קריאתחזרהנוכחית =
                    null;


                סגור();


                if (
                    קריאה
                ) {

                    קריאה(true);

                }

            }

        );

    }


    if (
        DOM.noButton
    ) {

        DOM.noButton.addEventListener(

            "click",

            () => {

                const קריאה =
                    קריאתחזרהנוכחית;


                קריאתחזרהנוכחית =
                    null;


                סגור();


                if (
                    קריאה
                ) {

                    קריאה(false);

                }

            }

        );

    }

}


/* =========================================================
   Export
========================================================= */

export {

    אתחלמודלאישור,

    בקשאישור

};
