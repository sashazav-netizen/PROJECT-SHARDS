/* =========================================================
   יצירת עותק חדש של גיבור
========================================================= */

/**
 * ניתן להעביר:
 *
 * 1. מפתח נתונים:
 *    "ברזילי"
 *
 * 2. ID:
 *    "barzilai"
 *
 * הפונקציה תמיד מחזירה עותק עצמאי.
 *
 * אנחנו לא מחזירים את אובייקט המקור.
 *
 * כך שינוי HP / XP / Stats
 * של גיבור במשחק לא משנה
 * את מאגר הנתונים המקורי.
 */

function צורעותקגיבור(
    מפתחאוID
) {

    if (
        !מפתחאוID
    ) {

        console.error(
            "[Hero Data] לא התקבל מפתח או ID של גיבור."
        );

        return null;

    }


    /* ---------------------------------------------
       חיפוש לפי מפתח
    --------------------------------------------- */

    let מקור =
        נתוני_גיבורים[
            מפתחאוID
        ];


    /* ---------------------------------------------
       אם לא נמצא — חיפוש לפי ID
    --------------------------------------------- */

    if (
        !מקור
    ) {

        const מפתח =
            Object.keys(
                נתוני_גיבורים
            ).find(

                מפתח =>

                    נתוני_גיבורים[
                        מפתח
                    ].id === מפתחאוID

            );


        if (
            מפתח
        ) {

            מקור =
                נתוני_גיבורים[
                    מפתח
                ];

        }

    }


    /* ---------------------------------------------
       גיבור לא נמצא
    --------------------------------------------- */

    if (
        !מקור
    ) {

        console.error(

            `[Hero Data] לא נמצא גיבור: ${מפתחאוID}`

        );

        return null;

    }


    /* ---------------------------------------------
       יצירת עותק עמוק
    --------------------------------------------- */

    try {

        return structuredClone(
            מקור
        );

    } catch (שגיאה) {

        console.error(

            "[Hero Data] שגיאה ביצירת עותק גיבור:",

            שגיאה

        );

        return null;

    }

}


