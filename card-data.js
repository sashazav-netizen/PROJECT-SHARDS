/* =========================================================
   עזר: יצירת עותק תבנית קלף
========================================================= */

function צורעותקכרטיס(
    id
) {

    const תבנית =
        נתוני_קלפים[
            id
        ];


    if (
        !תבנית
    ) {

        console.error(

            `[Card Data] לא נמצא קלף: ${id}`

        );

        return null;

    }


    try {

        return structuredClone(
            תבנית
        );

    } catch (שגיאה) {

        console.error(

            "[Card Data] שגיאה ביצירת עותק קלף:",

            שגיאה

        );

        return null;

    }

}


/* =========================================================
   קבלת כל מפתחות הקלפים
========================================================= */

function קבלכלמפתחותהקלפים() {

    return Object.keys(
        נתוני_קלפים
    );

}


/* =========================================================
   בניית חפיסת 30 קלפים לפי מחלקה
========================================================= */

/**
 * בונה מערך של 30 מזהי קלפים (עם כפילויות)
 * המתאים למחלקה מסוימת:
 *
 * - כל הקלפים האוניברסליים (מחלקה: null)
 * - + הקלפים הייחודיים למחלקה שהתבקשה
 *
 * אם המחלקה לא מוכרת / אין לה קלפים ייחודיים —
 * עדיין מוחזרת החפיסה האוניברסלית (20 קלפים),
 * כדי שלא תהיה חפיסה ריקה.
 */

function בנהחפיסהלמחלקה(
    מחלקה
) {

    const רשימה = [];


    for (
        const מפתח
        of קבלכלמפתחותהקלפים()
    ) {

        const תבנית =
            נתוני_קלפים[
                מפתח
            ];


        const שייךלמחלקה =

            תבנית.מחלקה === null

            ||

            (
                Array.isArray(תבנית.מחלקה) &&
                תבנית.מחלקה.includes(מחלקה)
            );


        if (
            !שייךלמחלקה
        ) {

            continue;

        }


        for (
            let i = 0;
            i < (תבנית.כמות_בחפיסה || 0);
            i++
        ) {

            רשימה.push(
                מפתח
            );

        }

    }


    return רשימה;

}


