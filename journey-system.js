/* =========================================================
   עזר: בחירה משוקללת
========================================================= */

/**
 * בוחר אירוע אחד ממאגר, לפי משקל יחסי.
 * ככל שהמשקל גבוה יותר — כך גדל הסיכוי שהאירוע ייבחר.
 */

function בחראירועמשוקלל(
    מאגר
) {

    if (
        !Array.isArray(מאגר) ||
        מאגר.length === 0
    ) {

        return null;

    }


    const סךהמשקלים =
        מאגר.reduce(

            (סכום, אירוע) =>
                סכום + (אירוע.משקל || 0),

            0

        );


    if (
        סךהמשקלים <= 0
    ) {

        return מאגר[0];

    }


    let גליל =
        Math.random() * סךהמשקלים;


    for (
        const אירוע
        of מאגר
    ) {

        גליל -=
            (אירוע.משקל || 0);


        if (
            גליל <= 0
        ) {

            return אירוע;

        }

    }


    return מאגר[
        מאגר.length - 1
    ];

}


/* =========================================================
   עזר: סינון אירועי גיבור שכבר קיימים
========================================================= */

/**
 * מסיר מהמאגר אירועי "גיבור" שהשחקן כבר פתח,
 * כדי שלא יוגרל שוב גיבור שכבר יש לו.
 */

function סנןאירועיגיבורקיימים(
    מאגר
) {

    const גיבוריםקיימים =
        קבלגיבוריהשחקן();


    const מפתחותקיימים =
        new Set(

            גיבוריםקיימים.map(

                גיבור =>
                    גיבור.שם_קצר

            )

        );


    return מאגר.filter(

        אירוע => {

            if (
                אירוע.סוג_תגמול !== "גיבור"
            ) {

                return true;

            }


            return !מפתחותקיימים.has(
                אירוע.מפתח_גיבור
            );

        }

    );

}


/* =========================================================
   עזר: מספר אקראי שלם בטווח
========================================================= */

function מספראקראיבטווח(
    מינימום,
    מקסימום
) {

    const מין =
        Number(מינימום) || 0;

    const מקס =
        Number(מקסימום) || מין;


    return (

        מין +

        Math.floor(
            Math.random() * (מקס - מין + 1)
        )

    );

}


/* =========================================================
   ביצוע מסע
========================================================= */

/**
 * מגרילה אירוע מסע, מעניקה את התגמול בפועל,
 * ומפרסמת "מסע_הושלם" עם תוצאת המסע המלאה.
 *
 * @returns {object|null} תוצאת המסע, או null אם נכשל.
 */

function בצעמסע() {

    const מאגרזמין =
        סנןאירועיגיבורקיימים(
            אירועי_מסע
        );


    const אירוע =
        בחראירועמשוקלל(
            מאגרזמין.length > 0
                ? מאגרזמין
                : אירועי_מסע
        );


    if (
        !אירוע
    ) {

        console.error(
            "[Journey System] לא נמצא אירוע מסע להגרלה."
        );

        return null;

    }


    const תוצאה = {

        אירוע_id:
            אירוע.id,

        כותרת:
            אירוע.כותרת,

        טקסט:
            אירוע.טקסט,

        סוג_תגמול:
            אירוע.סוג_תגמול,

        ערך: null,

        גיבור_חדש: null

    };


    /* ---------------------------------------------
       הענקת תגמול לפי סוג
    --------------------------------------------- */

    switch (אירוע.סוג_תגמול) {

        case "כסף":
        case "יהלומים": {

            const סכום =
                מספראקראיבטווח(

                    אירוע.מינימום,

                    אירוע.מקסימום

                );


            שנהמשאב(
                אירוע.סוג_תגמול,
                סכום
            );


            תוצאה.ערך =
                סכום;

            break;

        }


        case "ניסיון": {

            const סכום =
                מספראקראיבטווח(

                    אירוע.מינימום,

                    אירוע.מקסימום

                );


            const קבוצה =
                קבלגיבורי_הקבוצה();


            const יעד =

                קבוצה.length > 0
                    ? קבוצה
                    : קבלגיבוריהשחקן();


            יעד.forEach(

                גיבור =>

                    הוסףניסיון(

                        גיבור.id,

                        סכום

                    )

            );


            תוצאה.ערך =
                סכום;

            break;

        }


        case "גיבור": {

            const נפתח =
                פתחגיבור(

                    {
                        מפתח:
                            אירוע.מפתח_גיבור
                    }

                );


            if (
                נפתח
            ) {

                תוצאה.גיבור_חדש =
                    אירוע.מפתח_גיבור;

            } else {

                /*
                 * גיבור כבר קיים או שהפתיחה נכשלה —
                 * נופלים בחזרה לתגמול כסף קטן
                 * כדי שהשחקן לא יישאר בלי כלום.
                 */

                שנהמשאב(
                    "כסף",
                    20
                );


                תוצאה.סוג_תגמול =
                    "כסף";

                תוצאה.ערך =
                    20;

            }

            break;

        }


        default: {

            console.warn(

                `[Journey System] סוג תגמול לא מוכר: ${אירוע.סוג_תגמול}`

            );

        }

    }


    /* ---------------------------------------------
       ניסיון בסיסי — ניתן בכל מסע, בנוסף לתגמול
       העיקרי. כדי שהתקדמות תרגיש עקבית ולא תלויה
       רק בהגרלת אירוע "ניסיון" הייעודי (נדיר יחסית).
    --------------------------------------------- */

    const ניסיוןבסיסי =
        מספראקראיבטווח(
            5,
            10
        );


    const קבוצתבסיס =
        קבלגיבורי_הקבוצה();


    const יעדבסיס =

        קבוצתבסיס.length > 0
            ? קבוצתבסיס
            : קבלגיבוריהשחקן();


    יעדבסיס.forEach(

        גיבור =>

            הוסףניסיון(

                גיבור.id,

                ניסיוןבסיסי

            )

    );


    תוצאה.ניסיון_בסיסי =
        ניסיוןבסיסי;


    /* ---------------------------------------------
       עדכון מונה מסעות
    --------------------------------------------- */

    const מצב =
        קבלמצב();


    if (
        מצב &&
        מצב.התקדמות
    ) {

        מצב.התקדמות.מסעות_שהושלמו =

            (מצב.התקדמות.מסעות_שהושלמו || 0) + 1;

    }


    /* ---------------------------------------------
       פרסום אירוע
    --------------------------------------------- */

    פרסם(

        "מסע_הושלם",

        תוצאה

    );


    return תוצאה;

}


