/* =========================================================
   אתחול המשחק
========================================================= */

async function אתחלמשחק() {

    console.log(
        "[PROJECT SHARDS] אתחול המשחק..."
    );


    /* ---------------------------------------------
       מצב התחלתי
    --------------------------------------------- */

    שנהמסך(
        "טעינה"
    );


    /* ---------------------------------------------
       מסך טעינה
    --------------------------------------------- */

    await הצגטעינה();


    /* ---------------------------------------------
       אתחול מערכת גיבורים
    --------------------------------------------- */

    const מערכתגיבורים =
        אתחלמערכתגיבורים();


    if (!מערכתגיבורים) {

        console.error(
            "[PROJECT SHARDS] מערכת הגיבורים לא אותחלה."
        );

    } else {

        console.log(
            "[PROJECT SHARDS] מערכת הגיבורים מוכנה."
        );

    }


    /* ---------------------------------------------
       אתחול ממשק הגיבורים
       (נרשם לבדו לאירועי הגיבורים ומצייר את עצמו)
    --------------------------------------------- */

    אתחלממשקגיבורים();


    /* ---------------------------------------------
       אתחול ממשק המסע
    --------------------------------------------- */

    אתחלממשקמסע();


    /* ---------------------------------------------
       אתחול מערכת קלפים
    --------------------------------------------- */

    const מערכתקלפים =
        אתחלמערכתקלפים();


    if (!מערכתקלפים) {

        console.error(
            "[PROJECT SHARDS] מערכת הקלפים לא אותחלה."
        );

    } else {

        console.log(
            "[PROJECT SHARDS] מערכת הקלפים מוכנה."
        );

    }


    אתחלממשקקלפים();


    /* ---------------------------------------------
       אתחול ממשק הקרב
    --------------------------------------------- */

    אתחלממשקקרב();


    עלמעברלמסךקרב(

        () => {

            הצגמסךקרב();

        }

    );


    עלחזרהממסךקרב(

        מקור => {

            if (
                מקור === "מפה"
            ) {

                הצגמסךמפה();

            } else {

                הצגמסךמשחק();

            }

        }

    );


    /* ---------------------------------------------
       אתחול ממשק תיק וחנות
    --------------------------------------------- */

    אתחלממשקתיק();

    אתחלממשקחנות();


    /* ---------------------------------------------
       אתחול מערכת מפה וממשק המפה
    --------------------------------------------- */

    אתחלמערכתמפה();

    אתחלממשקמפה();


    /* ---------------------------------------------
       אתחול מודל אישור כללי
    --------------------------------------------- */

    אתחלמודלאישור();


    /* ---------------------------------------------
       חיבור אירועים
    --------------------------------------------- */

    חבראירועים();


    /* ---------------------------------------------
       חיבור ניווט
    --------------------------------------------- */

    חברניווט();


    /* ---------------------------------------------
       עדכון תפריט
    --------------------------------------------- */

    עדכןתפריט();


    /* ---------------------------------------------
       הצגת תפריט ראשי
    --------------------------------------------- */

    הצגמסךראשי();


    console.log(
        "[PROJECT SHARDS] המשחק מוכן."
    );

}


/* =========================================================
   מסך טעינה
========================================================= */

function הצגטעינה() {

    return new Promise(

        resolve => {

            let התקדמות = 0;


            const שלבים = [

                "מאתחל את העולם...",

                "טוען את ליבת המשחק...",

                "מכין את מצב השחקן...",

                "טוען את הגיבורים...",

                "מכין מערכות עתידיות...",

                "המערכת מוכנה."

            ];


            const interval =

                setInterval(

                    () => {

                        התקדמות +=
                            100 /
                            שלבים.length;


                        const אינדקס =

                            Math.min(

                                Math.floor(

                                    התקדמות /
                                    (
                                        100 /
                                        שלבים.length
                                    )

                                ),

                                שלבים.length - 1

                            );


                        if (
                            DOM.loadingProgress
                        ) {

                            DOM.loadingProgress.style.width =
                                `${Math.min(
                                    100,
                                    התקדמות
                                )}%`;

                        }


                        if (
                            DOM.loadingText
                        ) {

                            DOM.loadingText.textContent =
                                שלבים[
                                    אינדקס
                                ];

                        }


                        if (
                            התקדמות >= 100
                        ) {

                            clearInterval(
                                interval
                            );


                            setTimeout(

                                resolve,

                                350

                            );

                        }

                    },

                    180

                );

        }

    );

}


