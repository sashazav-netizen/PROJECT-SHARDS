/**
 * מופעלת באישור המודל (כפתור "התחל את המסע" בתוך המודל,
 * או Enter בתוך שדה השם).
 * מבצעת את כל יצירת המשחק החדש בפועל.
 */

function אשרשםואתחלמשחק() {

    const שם =

        DOM.nameModalInput
            ? DOM.nameModalInput.value
            : "";


    const שםנקי =
        שם.trim();


    /* ---------------------------------------------
       בדיקת שם
    --------------------------------------------- */

    if (
        שםנקי.length < 2
    ) {

        הצגשגיאתמודלשם(
            "השם חייב להכיל לפחות 2 תווים."
        );

        return;

    }


    if (
        שםנקי.length > 20
    ) {

        הצגשגיאתמודלשם(
            "השם יכול להכיל עד 20 תווים."
        );

        return;

    }


    הסתרשגיאתמודלשם();


    /* ---------------------------------------------
       איפוס State
    --------------------------------------------- */

    const אופס =
        אפסמצבמשחק();


    if (!אופס) {

        הצגשגיאתמודלשם(
            "לא ניתן לאפס את מצב המשחק."
        );

        return;

    }


    /* ---------------------------------------------
       יצירת פרופיל
    --------------------------------------------- */

    const פרופילנוצר =
        צורפרופיל(
            שםנקי
        );


    if (!פרופילנוצר) {

        הצגשגיאתמודלשם(
            "לא ניתן ליצור את פרופיל השחקן."
        );

        return;

    }


    /* ---------------------------------------------
       יצירת גיבורי התחלה
    --------------------------------------------- */

    const גיבוריםאופסו =
        אפסמערכתגיבורים();


    if (!גיבוריםאופסו) {

        הצגשגיאתמודלשם(
            "לא ניתן לאתחל את מערכת הגיבורים."
        );

        return;

    }


    /* ---------------------------------------------
       בניית חפיסת קלפים חדשה
       (חובה — אפסמצבמשחק() מרוקנת גם את החפיסה,
       בדיוק כמו שהגיבורים צריכים אתחול מחדש)
    --------------------------------------------- */

    const קלפיםאופסו =
        אתחלמערכתקלפים();


    if (!קלפיםאופסו) {

        הצגשגיאתמודלשם(
            "לא ניתן לאתחל את מערכת הקלפים."
        );

        return;

    }


    /* ---------------------------------------------
       עדכון תצוגה
    --------------------------------------------- */

    עדכןתצוגתשחקן();


    /* ---------------------------------------------
       שמירה ראשונה
    --------------------------------------------- */

    const נשמר =
        שמורמשחק();


    if (!נשמר) {

        הצגשגיאתמודלשם(
            "המשחק נוצר אך לא הצלחנו לשמור אותו."
        );

        return;

    }


    /* ---------------------------------------------
       עדכון תפריט
    --------------------------------------------- */

    עדכןתפריט();


    /* ---------------------------------------------
       אירוע
    --------------------------------------------- */

    פרסם(

        "שחקן_התחיל_משחק",

        {

            חדש:
                true,

            שם:
                שםנקי,

            זמן:
                Date.now()

        }

    );


    /* ---------------------------------------------
       סגירת המודל ומעבר למשחק
    --------------------------------------------- */

    סגורמודלשם();

    הצגמסךמשחק();


    if (
        DOM.gameMessage
    ) {

        DOM.gameMessage.textContent =

            `ברוך הבא, ${שםנקי}! המסע שלך מתחיל כאן.`;

    }


    console.log(

        `[PROJECT SHARDS] משחק חדש נוצר עבור ${שםנקי}.`

    );

}


/* =========================================================
   המשך משחק
========================================================= */

function המשךמשחק() {

    console.log(
        "[PROJECT SHARDS] טעינת משחק שמור..."
    );


    /* ---------------------------------------------
       בדיקת שמירה
    --------------------------------------------- */

    if (
        !ישמשחקקיים()
    ) {

        alert(
            "לא נמצא משחק שמור."
        );

        עדכןתפריט();

        return;

    }


    /* ---------------------------------------------
       טעינת State
    --------------------------------------------- */

    const נטען =
        טעןמשחק();


    if (!נטען) {

        alert(
            "טעינת המשחק נכשלה."
        );

        return;

    }


    /* ---------------------------------------------
       טעינת Hero System
    --------------------------------------------- */

    const גיבוריםנטענו =
        אתחלמערכתגיבורים();


    if (!גיבוריםנטענו) {

        alert(
            "טעינת הגיבורים נכשלה."
        );

        return;

    }


    /* ---------------------------------------------
       טעינת Card System
       (אם לשחקן ישן אין עדיין חפיסה — תיבנה כאן)
    --------------------------------------------- */

    אתחלמערכתקלפים();

    אתחלממשקקלפים();


    /* ---------------------------------------------
       טעינת Map System
       (תיקון עצמי לשמירות ישנות בלי שדות מפה)
    --------------------------------------------- */

    אתחלמערכתמפה();


    /* ---------------------------------------------
       קבלת State
    --------------------------------------------- */

    const מצב =
        קבלמצב();


    const שם =

        מצב.פרופיל?.שם
        ||
        מצב.שחקן?.שם
        ||
        "נוסע";


    /* ---------------------------------------------
       עדכון UI
    --------------------------------------------- */

    עדכןתצוגתשחקן();


    /* ---------------------------------------------
       אירוע
    --------------------------------------------- */

    פרסם(

        "שחקן_התחיל_משחק",

        {

            חדש:
                false,

            שם,

            זמן:
                Date.now()

        }

    );


    /* ---------------------------------------------
       מעבר למשחק
    --------------------------------------------- */

    הצגמסךמשחק();


    if (
        DOM.gameMessage
    ) {

        DOM.gameMessage.textContent =

            `ברוך שובך, ${שם}!`;

    }


    console.log(

        `[PROJECT SHARDS] המשחק נטען עבור ${שם}.`

    );

}


