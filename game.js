/* =========================================================
   עדכון תצוגת השחקן
========================================================= */

function עדכןתצוגתשחקן() {

    const מצב =
        קבלמצב();


    if (
        !מצב
    ) {

        return;

    }


    const שחקן =
        מצב.שחקן;


    if (
        !שחקן
    ) {

        return;

    }


    /* ---------------------------------------------
       שם
    --------------------------------------------- */

    if (
        DOM.playerName
    ) {

        DOM.playerName.textContent =

            מצב.פרופיל?.שם
            ||
            שחקן.שם
            ||
            "נוסע";

    }


    /* ---------------------------------------------
       רמה
       (מחושבת: הרמה הגבוהה ביותר מבין הגיבורים
       שברשות השחקן — אין עדיין "רמת שחקן" נפרדת,
       זו הצגה משמעותית במקום שדה סטטי שלא זז)
    --------------------------------------------- */

    if (
        DOM.playerLevel
    ) {

        const גיבורים =
            קבלגיבוריהשחקן();


        const רמהגבוהה =

            גיבורים.reduce(

                (מקסימלי, גיבור) =>

                    Math.max(

                        מקסימלי,

                        גיבור.progression?.level || 1

                    ),

                1

            );


        DOM.playerLevel.textContent =
            רמהגבוהה;

    }


    /* ---------------------------------------------
       כסף
    --------------------------------------------- */

    if (
        DOM.playerMoney
    ) {

        DOM.playerMoney.textContent =

            Number.isFinite(
                שחקן.כסף
            )
                ? שחקן.כסף
                : 0;

    }


    /* ---------------------------------------------
       זהב
    --------------------------------------------- */

    if (
        DOM.playerGold
    ) {

        DOM.playerGold.textContent =

            Number.isFinite(
                שחקן.זהב
            )
                ? שחקן.זהב
                : 0;

    }


    /* ---------------------------------------------
       יהלומים
    --------------------------------------------- */

    if (
        DOM.playerDiamonds
    ) {

        DOM.playerDiamonds.textContent =

            Number.isFinite(
                שחקן.יהלומים
            )
                ? שחקן.יהלומים
                : 0;

    }

}


