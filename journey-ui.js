import {

    בצעמסע

} from "./journey-system.js";


import {

    הירשם

} from "../core/events.js";


import {

    קבלמצב

} from "../core/state.js";


/* =========================================================
   DOM
========================================================= */

const DOM = {

    כפתור:
        document.getElementById(
            "journey-button"
        ),

    תוצאה:
        document.getElementById(
            "journey-result"
        ),

    מונה:
        document.getElementById(
            "journey-counter"
        )

};


/* =========================================================
   אייקון לפי סוג תגמול
========================================================= */

function אייקוןלתגמול(
    סוג
) {

    switch (סוג) {

        case "כסף":
            return "💰";

        case "יהלומים":
            return "💎";

        case "ניסיון":
            return "✨";

        case "גיבור":
            return "🌟";

        default:
            return "✦";

    }

}


/* =========================================================
   טקסט תגמול קריא
========================================================= */

function טקסטתגמול(
    תוצאה
) {

    const שורתבסיס =

        תוצאה.ניסיון_בסיסי
            ? `\n+${תוצאה.ניסיון_בסיסי} ניסיון לקבוצה`
            : "";


    switch (תוצאה.סוג_תגמול) {

        case "כסף":
            return `+${תוצאה.ערך} כסף${שורתבסיס}`;

        case "יהלומים":
            return `+${תוצאה.ערך} יהלומים${שורתבסיס}`;

        case "ניסיון":
            return `+${תוצאה.ערך} ניסיון לכל הקבוצה${שורתבסיס}`;

        case "גיבור":
            return `גיבור חדש: ${תוצאה.גיבור_חדש}!${שורתבסיס}`;

        default:
            return שורתבסיס;

    }

}


/* =========================================================
   הצגת תוצאת מסע
========================================================= */

function הצגתוצאתמסע(
    תוצאה
) {

    if (
        !DOM.תוצאה ||
        !תוצאה
    ) {

        return;

    }


    const מיוחד =
        תוצאה.סוג_תגמול === "גיבור" &&
        תוצאה.גיבור_חדש;


    DOM.תוצאה.innerHTML =
        "";


    DOM.תוצאה.classList.remove(
        "hidden"
    );


    DOM.תוצאה.classList.toggle(
        "journey-result-special",
        !!מיוחד
    );


    const אייקון =
        document.createElement(
            "span"
        );

    אייקון.className =
        "journey-result-icon";

    אייקון.textContent =
        אייקוןלתגמול(
            תוצאה.סוג_תגמול
        );


    const כותרת =
        document.createElement(
            "h3"
        );

    כותרת.className =
        "journey-result-title";

    כותרת.textContent =
        תוצאה.כותרת;


    const טקסט =
        document.createElement(
            "p"
        );

    טקסט.className =
        "journey-result-text";

    טקסט.textContent =
        תוצאה.טקסט;


    const תגמול =
        document.createElement(
            "p"
        );

    תגמול.className =
        "journey-result-reward";

    תגמול.textContent =
        טקסטתגמול(
            תוצאה
        );


    DOM.תוצאה.appendChild(
        אייקון
    );

    DOM.תוצאה.appendChild(
        כותרת
    );

    DOM.תוצאה.appendChild(
        טקסט
    );

    DOM.תוצאה.appendChild(
        תגמול
    );

}


/* =========================================================
   עדכון מונה מסעות
========================================================= */

function עדכןמונהמסעות() {

    if (
        !DOM.מונה
    ) {

        return;

    }


    const מצב =
        קבלמצב();


    const מספר =

        (מצב &&
        מצב.התקדמות &&
        מצב.התקדמות.מסעות_שהושלמו)

            || 0;


    DOM.מונה.textContent =

        `מסעות שהושלמו: ${מספר}`;

}


/* =========================================================
   טיפול בלחיצה על "צא למסע"
========================================================= */

function טפללחיצתמסע() {

    if (
        DOM.כפתור
    ) {

        DOM.כפתור.disabled =
            true;

    }


    const תוצאה =
        בצעמסע();


    if (
        DOM.כפתור
    ) {

        DOM.כפתור.disabled =
            false;

    }


    if (
        !תוצאה
    ) {

        console.error(
            "[Journey UI] המסע נכשל."
        );

    }

}


/* =========================================================
   אתחול
========================================================= */

function אתחלממשקמסע() {

    if (
        DOM.כפתור
    ) {

        DOM.כפתור.addEventListener(

            "click",

            טפללחיצתמסע

        );

    }


    הירשם(

        "מסע_הושלם",

        תוצאה => {

            הצגתוצאתמסע(
                תוצאה
            );

            עדכןמונהמסעות();

        }

    );


    עדכןמונהמסעות();

}


/* =========================================================
   Export
========================================================= */

export {

    אתחלממשקמסע

};
