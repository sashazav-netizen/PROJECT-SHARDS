/* =========================================================
   בדיקת תקינות
========================================================= */

function בדוקתקינותגיבורים() {

    const גיבורים =
        קבלגיבוריהשחקן();


    const בעיות = [];


    for (

        const גיבור
        of
        גיבורים

    ) {

        if (!גיבור.id) {

            בעיות.push(
                "גיבור ללא ID"
            );

        }


        if (!גיבור.stats) {

            בעיות.push(

                `${גיבור.שם || "גיבור"} ללא Stats`

            );


            continue;

        }


        if (

            גיבור.stats.maxHp < 0

        ) {

            בעיות.push(

                `${גיבור.שם} - Max HP שלילי`

            );

        }


        if (

            גיבור.stats.hp < 0

        ) {

            בעיות.push(

                `${גיבור.שם} - HP שלילי`

            );

        }


        if (

            גיבור.stats.hp
            >
            גיבור.stats.maxHp

        ) {

            בעיות.push(

                `${גיבור.שם} - HP גבוה מ-Max HP`

            );

        }


        if (

            גיבור.stats.maxEnergy < 0

        ) {

            בעיות.push(

                `${גיבור.שם} - Max Energy שלילי`

            );

        }


        if (

            גיבור.stats.energy < 0

        ) {

            בעיות.push(

                `${גיבור.שם} - Energy שלילי`

            );

        }


        if (

            גיבור.stats.energy
            >
            גיבור.stats.maxEnergy

        ) {

            בעיות.push(

                `${גיבור.שם} - Energy גבוה מהמקסימום`

            );

        }


        if (

            גיבור.stats.maxBreakPower < 0

        ) {

            בעיות.push(

                `${גיבור.שם} - Max Break Power שלילי`

            );

        }


        if (

            גיבור.stats.breakPower < 0

        ) {

            בעיות.push(

                `${גיבור.שם} - Break Power שלילי`

            );

        }


        if (

            גיבור.stats.breakPower
            >
            גיבור.stats.maxBreakPower

        ) {

            בעיות.push(

                `${גיבור.שם} - Break Power גבוה מהמקסימום`

            );

        }


        if (

            !גיבור.progression

        ) {

            בעיות.push(

                `${גיבור.שם} - חסר Progression`

            );

        }

    }


    const קבוצה =
        קבלגיבורי_הקבוצה();


    if (

        קבוצה.length
        >
        גודל_קבוצה_מקסימלי

    ) {

        בעיות.push(
            "הקבוצה גדולה מהמותר."
        );

    }


    const IDs = [
        ...קבוצת_הגיבורים
    ];


    const IDsייחודיים =
        new Set(
            IDs
        );


    if (

        IDs.length
        !==
        IDsייחודיים.size

    ) {

        בעיות.push(
            "הקבוצה מכילה גיבור כפול."
        );

    }


    for (

        const id
        of
        קבוצת_הגיבורים

    ) {

        if (
            !גיבורי_השחקן.has(id)
        ) {

            בעיות.push(

                `הקבוצה מכילה גיבור שאינו קיים: ${id}`

            );

        }

    }


    if (
        גיבור_נבחר_id
        &&
        !גיבורי_השחקן.has(
            גיבור_נבחר_id
        )
    ) {

        בעיות.push(

            `הגיבור הנבחר אינו קיים: ${גיבור_נבחר_id}`

        );

    }


    return {

        תקין:
            בעיות.length === 0,

        בעיות,

        מספרגיבורים:
            גיבורים.length,

        גודל_קבוצה:
            קבוצה.length

    };

}


