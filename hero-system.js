/* =========================================================
   איפוס מערכת — משחק חדש
========================================================= */

function אפסמערכתגיבורים() {

    גיבורי_השחקן.clear();

    קבוצת_הגיבורים.length = 0;

    גיבור_נבחר_id = null;


    const מצב =
        קבלמצב();


    מצב.גיבורים = [];

    מצב.קבוצת_גיבורים = [];


    for (

        const מפתח
        of
        גיבורי_התחלה

    ) {

        הוסףגיבורמהנתונים(
            מפתח
        );

    }


    const גיבורים =
        קבלגיבוריהשחקן();


    if (
        גיבורים.length > 0
    ) {

        קבוצת_הגיבורים.push(
            גיבורים[0].id
        );


        גיבור_נבחר_id =
            גיבורים[0].id;


        בחרגיבור(
            גיבורים[0].id
        );

    }


    עדכןבחירתגיבורים();

    סנכרןלמצב();


    פרסם(

        "קבוצת_הגיבורים_השתנתה",

        {

            קבוצה:
                קבלגיבורי_הקבוצה()

        }

    );


    console.log(

        "[Hero System] מערכת הגיבורים אופסה למשחק חדש."

    );


    return true;

}


