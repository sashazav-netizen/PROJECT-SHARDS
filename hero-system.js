/* =========================================================
   פתיחת גיבור
========================================================= */

function פתחגיבור(
    נתוני_גיבור
) {

    if (!נתוני_גיבור) {

        return false;

    }


    /*
     * אפשרות 1:
     * קיבלנו אובייקט עם מפתח.
     */

    if (
        נתוני_גיבור.מפתח
    ) {

        const קיים =
            גיבורי_השחקן.values();


        /*
         * מונעים יצירה כפולה
         * לפני יצירת העותק.
         */

        const עותק =
            צורעותקגיבור(
                נתוני_גיבור.מפתח
            );


        if (!עותק) {

            return false;

        }


        if (
            גיבורי_השחקן.has(
                עותק.id
            )
        ) {

            return false;

        }


        עותק.unlocked =
            true;


        עותק.selected =
            false;


        גיבורי_השחקן.set(

            עותק.id,

            עותק

        );


        סנכרןלמצב();


        פרסם(

            "גיבור_נפתח",

            {

                גיבור:
                    עותק

            }

        );


        return true;

    }


    /*
     * אפשרות 2:
     * התקבל ID.
     *
     * hero-data.js כרגע אינו מספק
     * פונקציה ישירה לקבלת עותק לפי ID.
     *
     * לכן לא ננסה לנחש מפתח.
     */

    if (
        נתוני_גיבור.id
    ) {

        console.warn(

            `[Hero System] פתיחת גיבור לפי ID אינה נתמכת כרגע ללא מפתח נתונים: ${נתוני_גיבור.id}`

        );

    }


    return false;

}


