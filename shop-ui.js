import {

    קבלמלאיחנות,

    קנהחפץ

} from "./shop-system.js";


import {

    אייקוןלסוגחפץ

} from "../items/item-data.js";


import {

    בקשאישור

} from "../core/confirm-modal.js";


/* =========================================================
   DOM
========================================================= */

const DOM = {

    items:
        document.getElementById(
            "shop-items"
        )

};


/* =========================================================
   הגנה בסיסית לפני הכנסת טקסט ל-innerHTML
========================================================= */

function ברח_טקסט(
    טקסט
) {

    const div =
        document.createElement(
            "div"
        );


    div.textContent =
        טקסט ?? "";


    return div.innerHTML;

}


/* =========================================================
   טקסט מחיר קריא
========================================================= */

function טקסטמחיר(
    מחיר
) {

    const חלקים = [];


    if (
        מחיר.כסף > 0
    ) {

        חלקים.push(

            `${מחיר.כסף} 🪙`

        );

    }


    if (
        מחיר.יהלומים > 0
    ) {

        חלקים.push(

            `${מחיר.יהלומים} 💎`

        );

    }


    return חלקים.join(" · ")
        || "חינם";

}


/* =========================================================
   ציור מלאי החנות
========================================================= */

function צייררחנות() {

    if (
        !DOM.items
    ) {

        return;

    }


    const מלאי =
        קבלמלאיחנות();


    DOM.items.innerHTML =
        "";


    מלאי.forEach(

        חפץ => {

            const בונוסים =
                Object.entries(
                    חפץ.בונוסים || {}
                )

                    .map(

                        ([מפתח, ערך]) =>

                            `+${ערך} ${מפתח}`

                    )

                    .join(" · ");


            const card =
                document.createElement(
                    "article"
                );

            card.className =
                "card-tile";


            card.innerHTML = `

                <div class="card-tile-top">

                    <span class="card-tile-icon">
                        ${אייקוןלסוגחפץ(חפץ.סוג)}
                    </span>

                    <span class="card-tile-cost">
                        ${ברח_טקסט(חפץ.נדירות)}
                    </span>

                </div>

                <h3 class="card-tile-name">
                    ${ברח_טקסט(חפץ.שם)}
                </h3>

                <p class="card-tile-description">
                    ${ברח_טקסט(חפץ.תיאור)}
                </p>

                <div class="card-tile-effects">
                    ${ברח_טקסט(בונוסים)}
                </div>

            `;


            const כפתורקנייה =
                document.createElement(
                    "button"
                );

            כפתורקנייה.type =
                "button";

            כפתורקנייה.className =
                "primary-button shop-buy-button";

            כפתורקנייה.textContent =

                `קנה — ${טקסטמחיר(חפץ.מחיר || {})}`;


            כפתורקנייה.addEventListener(

                "click",

                () => {

                    בקשאישור(

                        {

                            כותרת:
                                `לקנות ${חפץ.שם}?`,

                            הודעה:
                                `המחיר: ${טקסטמחיר(חפץ.מחיר || {})}`,

                            טקסטאישור:
                                "קנה"

                        },

                        אושר => {

                            if (
                                !אושר
                            ) {

                                return;

                            }


                            const תוצאה =
                                קנהחפץ(
                                    חפץ.מפתח
                                );


                            if (
                                !תוצאה.הצלחה
                            ) {

                                כפתורקנייה.classList.add(
                                    "shake"
                                );


                                setTimeout(

                                    () => {

                                        כפתורקנייה.classList.remove(
                                            "shake"
                                        );

                                    },

                                    400

                                );

                            }

                        }

                    );

                }

            );


            card.appendChild(
                כפתורקנייה
            );


            DOM.items.appendChild(
                card
            );

        }

    );

}


/* =========================================================
   אתחול
========================================================= */

function אתחלממשקחנות() {

    צייררחנות();

}


/* =========================================================
   Export
========================================================= */

export {

    אתחלממשקחנות

};
