/* =========================================================
   הגדרות כלכלת תחייה
========================================================= */

const עלות_תחייה_כסף = 20;

const עלות_תחייה_יהלומים = 2;

const זמן_תחייה_מילישניות =

    3 * 60 * 1000;
    // 3 דקות — פרק זמן קצר בכוונה, כדי לא להעניש יותר מדי
    // בשלב הזה של הפיתוח. אפשר לכוונן בהמשך.


/* =========================================================
   אתחול / תיקון עצמי לשמירות ישנות
========================================================= */

function אתחלמערכתמפה() {

    const מצב =
        קבלמצב();


    if (
        !מצב ||
        !מצב.התקדמות
    ) {

        return false;

    }


    if (
        !Number.isFinite(מצב.התקדמות.מפה_אינדקס)
    ) {

        מצב.התקדמות.מפה_אינדקס =
            0;

    }


    if (
        מצב.התקדמות.מפה_נפילה_עד === undefined
    ) {

        מצב.התקדמות.מפה_נפילה_עד =
            null;

    }


    if (
        מצב.התקדמות.מפה_נופל_גיבור_id === undefined
    ) {

        מצב.התקדמות.מפה_נופל_גיבור_id =
            null;

    }


    return true;

}


/* =========================================================
   מיקום נוכחי במפה
========================================================= */

function קבלאינדקסנוכחי() {

    const מצב =
        קבלמצב();


    const גודל =
        קבלגודלמפה();


    if (
        !מצב ||
        !מצב.התקדמות ||
        גודל === 0
    ) {

        return 0;

    }


    return (
        (מצב.התקדמות.מפה_אינדקס || 0) % גודל
    );

}


function קבלנקודהנוכחית() {

    return קבלנקודהלפיאינדקס(

        קבלאינדקסנוכחי()

    );

}


/* =========================================================
   מצב נפילה (תחייה)
========================================================= */

/**
 * בודק אם השחקן כרגע "נופל" (הפסיד בקרב-מפה
 * וטרם התאושש). אם הזמן כבר עבר — מתאושש אוטומטית.
 */

function האםנופל() {

    const מצב =
        קבלמצב();


    if (
        !מצב ||
        !מצב.התקדמות ||
        !מצב.התקדמות.מפה_נפילה_עד
    ) {

        return false;

    }


    if (
        Date.now() >= מצב.התקדמות.מפה_נפילה_עד
    ) {

        בטלנפילה();

        return false;

    }


    return true;

}


function זמןנותרלתחייהmsec() {

    const מצב =
        קבלמצב();


    if (
        !מצב ||
        !מצב.התקדמות ||
        !מצב.התקדמות.מפה_נפילה_עד
    ) {

        return 0;

    }


    return Math.max(

        0,

        מצב.התקדמות.מפה_נפילה_עד - Date.now()

    );

}


/**
 * מבטל את מצב הנפילה ומרפא את הגיבור שנפל —
 * בין אם כי הזמן עבר, ובין אם כי שולם עבור החייאה.
 */

function בטלנפילה() {

    const מצב =
        קבלמצב();


    if (
        !מצב ||
        !מצב.התקדמות
    ) {

        return;

    }


    const idגיבורנופל =
        מצב.התקדמות.מפה_נופל_גיבור_id;


    מצב.התקדמות.מפה_נפילה_עד =
        null;

    מצב.התקדמות.מפה_נופל_גיבור_id =
        null;


    if (
        idגיבורנופל
    ) {

        אפסגיבור(
            idגיבורנופל
        );

    }


    פרסם(

        "מפה_תחייה",

        {

            idגיבור:
                idגיבורנופל

        }

    );

}


/* =========================================================
   תשלום עבור החייאה מיידית
========================================================= */

function שלםתחייהבכסף() {

    if (
        !האםנופל()
    ) {

        return false;

    }


    const מצב =
        קבלמצב();


    if (
        (מצב.שחקן.כסף || 0) < עלות_תחייה_כסף
    ) {

        return false;

    }


    שנהמשאב(
        "כסף",
        -עלות_תחייה_כסף
    );


    בטלנפילה();


    return true;

}


function שלםתחייהביהלומים() {

    if (
        !האםנופל()
    ) {

        return false;

    }


    const מצב =
        קבלמצב();


    if (
        (מצב.שחקן.יהלומים || 0) < עלות_תחייה_יהלומים
    ) {

        return false;

    }


    שנהמשאב(
        "יהלומים",
        -עלות_תחייה_יהלומים
    );


    בטלנפילה();


    return true;

}


/* =========================================================
   התקדמות לנקודה הבאה
========================================================= */

function התקדם() {

    const מצב =
        קבלמצב();


    if (
        !מצב ||
        !מצב.התקדמות
    ) {

        return;

    }


    const גודל =
        קבלגודלמפה();


    מצב.התקדמות.מפה_אינדקס =

        (
            (מצב.התקדמות.מפה_אינדקס || 0) + 1
        )
        % גודל;


    פרסם(

        "מפה_התקדמה",

        {

            אינדקסחדש:
                מצב.התקדמות.מפה_אינדקס

        }

    );

}


/* =========================================================
   יציאה לקרב מהמפה
========================================================= */

function צאלקרבמפה(
    idגיבור
) {

    if (
        האםנופל()
    ) {

        console.warn(

            "[Map System] לא ניתן לצאת לקרב — גיבור נופל."

        );

        return false;

    }


    const נקודה =
        קבלנקודהנוכחית();


    if (

        !נקודה
        ||
        (
            נקודה.סוג !== סוגי_נקודות.BATTLE &&
            נקודה.סוג !== סוגי_נקודות.BOSS
        )

    ) {

        console.warn(

            "[Map System] הנקודה הנוכחית אינה קרב."

        );

        return false;

    }


    return התחלקרב(

        idגיבור,

        נקודה.מפתחאויב,

        "מפה"

    );

}


/* =========================================================
   יציאה למסע מהמפה
========================================================= */

function צאלמסעמפה() {

    if (
        האםנופל()
    ) {

        return null;

    }


    const נקודה =
        קבלנקודהנוכחית();


    if (
        !נקודה ||
        נקודה.סוג !== סוגי_נקודות.JOURNEY
    ) {

        return null;

    }


    const תוצאה =
        בצעמסע();


    if (
        תוצאה
    ) {

        התקדם();

    }


    return תוצאה;

}


/* =========================================================
   סיום בחנות והתקדמות
========================================================= */

function סייםבחנותמפה() {

    if (
        האםנופל()
    ) {

        return false;

    }


    const נקודה =
        קבלנקודהנוכחית();


    if (
        !נקודה ||
        נקודה.סוג !== סוגי_נקודות.SHOP
    ) {

        return false;

    }


    התקדם();


    return true;

}


/* =========================================================
   האזנה לתוצאות קרב שמקורן במפה
========================================================= */

הירשם(

    "קרב_הסתיים",

    נתונים => {

        if (
            !נתונים ||
            נתונים.מקור !== "מפה"
        ) {

            return;

        }


        if (
            נתונים.תוצאה === "ניצחון"
        ) {

            התקדם();

            return;

        }


        if (
            נתונים.תוצאה === "הפסד"
        ) {

            const מצב =
                קבלמצב();


            if (
                מצב &&
                מצב.התקדמות
            ) {

                מצב.התקדמות.מפה_נפילה_עד =

                    Date.now() + זמן_תחייה_מילישניות;


                מצב.התקדמות.מפה_נופל_גיבור_id =

                    נתונים.גיבורId;

            }


            פרסם(

                "מפה_נפילה",

                {

                    idגיבור:
                        נתונים.גיבורId,

                    עדזמן:
                        מצב && מצב.התקדמות
                            ? מצב.התקדמות.מפה_נפילה_עד
                            : null

                }

            );

        }

    }

);


