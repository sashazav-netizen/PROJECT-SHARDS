import {

    צורעותקכרטיס,

    קבלכלמפתחותהקלפים,

    בנהחפיסהלמחלקה

} from "./card-data.js";


import {

    קבלמצב

} from "../core/state.js";


import {

    פרסם

} from "../core/events.js";


/* =========================================================
   מצב זמני של קרב (לא נשמר)
========================================================= */

let חפיסת_משיכה = [];

let יד_נוכחית = [];

let ערמת_פסולת = [];

let מונה_מזהים = 0;


/* =========================================================
   עזר: מזהה ייחודי למופע קלף
========================================================= */

/**
 * לכל עותק פיזי של קלף ביד/בחפיסה יש instanceId משלו,
 * כדי שנוכל להבדיל בין שני "מכת חרב" זהים ביד.
 */

function מזההחדש() {

    מונה_מזהים += 1;


    return `card-${מונה_מזהים}`;

}


/* =========================================================
   אתחול אוסף הקלפים והחפיסה של השחקן
========================================================= */

/**
 * אם לשחקן אין עדיין אוסף קלפים (משחק חדש) —
 * פותחים לו את כל תבניות הקלפים הבסיסיות כברירת מחדל,
 * ובונים חפיסת 30 קלפים סטנדרטית.
 *
 * אם יש כבר נתונים (טעינת משחק) — לא נוגעים בהם.
 */

function אתחלמערכתקלפים() {

    const מצב =
        קבלמצב();


    if (
        !מצב
    ) {

        console.error(
            "[Card System] אין מצב משחק זמין."
        );

        return false;

    }


    if (
        !Array.isArray(מצב.קלפים) ||
        מצב.קלפים.length === 0
    ) {

        מצב.קלפים =
            קבלכלמפתחותהקלפים();


        console.log(

            `[Card System] נפתחו ${מצב.קלפים.length} סוגי קלפים בסיסיים.`

        );

    }


    if (
        !Array.isArray(מצב.חפיסה) ||
        מצב.חפיסה.length === 0
    ) {

        /*
         * הערה: מצב.חפיסה הגלובלי הוא שדה legacy
         * מהשלב שלפני חפיסות ייחודיות לכל גיבור.
         * הקרב האמיתי משתמש בחפיסה של הגיבור עצמו
         * (גיבור.deck), לא בשדה הזה.
         * הוא נשמר כאן רק כ-fallback בטוח למקרה קצה.
         */

        מצב.חפיסה =
            בנהחפיסהלמחלקה(
                "לוחם"
            );


        console.log(

            `[Card System] נבנתה חפיסת ברירת מחדל (legacy) עם ${מצב.חפיסה.length} קלפים.`

        );

    }


    פרסם(

        "קלפים_נטענו",

        {

            כמותקלפיםבחפיסה:
                מצב.חפיסה.length,

            כמותסוגיםפתוחים:
                מצב.קלפים.length

        }

    );


    return true;

}


/* =========================================================
   קבלת חפיסה עבור גיבור ספציפי
========================================================= */

/**
 * מחזיר את רשימת הקלפים של הגיבור (30 קלפים).
 *
 * אם לגיבור אין עדיין חפיסה תקינה (גיבור חדש/ישן
 * שנוצר לפני שהיו חפיסות ייחודיות) — בונים לו אחת
 * חדשה לפי המחלקה שלו ומחזירים אותה. קריאה זו
 * אינה שומרת את החפיסה בחזרה על הגיבור — זו אחריות
 * הקוד הקורא (למשל battle-system.js), כדי ש-card-system.js
 * לא ייגע ישירות באובייקט הגיבור של hero-system.js.
 */

function קבלחפיסתגיבור(
    גיבור
) {

    if (
        !גיבור
    ) {

        return [];

    }


    if (
        Array.isArray(גיבור.deck) &&
        גיבור.deck.length > 0
    ) {

        return גיבור.deck;

    }


    console.warn(

        `[Card System] לגיבור ${גיבור.id} אין חפיסה — בונה חפיסה חדשה לפי מחלקה (${גיבור.class}).`

    );


    return בנהחפיסהלמחלקה(
        גיבור.class
    );

}


/* =========================================================
   ערבוב (Fisher-Yates)
========================================================= */

function ערבב(
    מערך
) {

    const תוצאה =
        [...מערך];


    for (
        let i = תוצאה.length - 1;
        i > 0;
        i--
    ) {

        const j =
            Math.floor(
                Math.random() * (i + 1)
            );


        [תוצאה[i], תוצאה[j]] =

            [תוצאה[j], תוצאה[i]];

    }


    return תוצאה;

}


/* =========================================================
   התחלת קרב — איפוס ובניית חפיסת משיכה
========================================================= */

/**
 * לוקח את מצב.חפיסה (רשימת מזהי קלפים שהשחקן בנה)
 * והופך אותה לחפיסת משיכה מעורבבת עם instanceId לכל קלף.
 * מרוקן יד וערמת פסולת.
 */

/**
 * מתחיל חפיסת קרב חדשה.
 *
 * @param {string[]} [רשימתקלפים] - רשימת מזהי קלפים (חפיסת הגיבור
 *   הספציפי שנלחם). אם לא הועברה, נופל בחזרה למצב.חפיסה
 *   הגלובלי (לתאימות לאחור בלבד).
 */

function התחלחפיסתקרב(
    רשימתקלפים
) {

    const מקור =

        Array.isArray(רשימתקלפים) && רשימתקלפים.length > 0

            ? רשימתקלפים

            : קבלמצב()?.חפיסה;


    if (
        !Array.isArray(מקור) ||
        מקור.length === 0
    ) {

        console.error(
            "[Card System] אין חפיסה תקינה להתחלת קרב."
        );

        return false;

    }


    const מופעים =
        מקור

            .map(
                מפתח => {

                    const קלף =
                        צורעותקכרטיס(
                            מפתח
                        );


                    if (
                        !קלף
                    ) {

                        return null;

                    }


                    return {

                        ...קלף,

                        instanceId:
                            מזההחדש()

                    };

                }

            )

            .filter(Boolean);


    חפיסת_משיכה =
        ערבב(
            מופעים
        );

    יד_נוכחית = [];

    ערמת_פסולת = [];


    פרסם(

        "חפיסה_אותחלה",

        {

            גודל:
                חפיסת_משיכה.length

        }

    );


    return true;

}


/* =========================================================
   משיכת קלפים
========================================================= */

/**
 * מושך N קלפים מחפיסת המשיכה אל היד.
 * אם חפיסת המשיכה נגמרת באמצע — ערמת הפסולת
 * מתערבבת מחדש והופכת לחפיסת משיכה חדשה.
 */

function משוךקלפים(
    כמות = 1
) {

    const נמשכו = [];


    for (
        let i = 0;
        i < כמות;
        i++
    ) {

        if (
            חפיסת_משיכה.length === 0
        ) {

            if (
                ערמת_פסולת.length === 0
            ) {

                /* אין יותר קלפים בכלל — עוצרים */

                break;

            }


            חפיסת_משיכה =
                ערבב(
                    ערמת_פסולת
                );

            ערמת_פסולת = [];


            פרסם(

                "ערמת_פסולת_עורבבה_מחדש",

                {

                    גודל:
                        חפיסת_משיכה.length

                }

            );

        }


        const קלף =
            חפיסת_משיכה.shift();


        if (
            קלף
        ) {

            יד_נוכחית.push(
                קלף
            );

            נמשכו.push(
                קלף
            );

        }

    }


    פרסם(

        "קלפים_נמשכו",

        {

            קלפים:
                נמשכו,

            גודליד:
                יד_נוכחית.length

        }

    );


    return נמשכו;

}


/* =========================================================
   שיחוק קלף
========================================================= */

/**
 * מוציא קלף מהיד לפי instanceId.
 * קלף עם שריפה=true לא חוזר לשום מקום.
 * אחרת — עובר לערמת הפסולת.
 *
 * @returns הקלף ששוחק, או null אם לא נמצא.
 */

function שחקקלף(
    instanceId
) {

    const אינדקס =
        יד_נוכחית.findIndex(

            קלף =>
                קלף.instanceId === instanceId

        );


    if (
        אינדקס === -1
    ) {

        console.warn(

            `[Card System] קלף לא נמצא ביד: ${instanceId}`

        );

        return null;

    }


    const [קלף] =
        יד_נוכחית.splice(
            אינדקס,
            1
        );


    if (
        קלף.שריפה
    ) {

        פרסם(

            "קלף_נשרף",

            {
                קלף
            }

        );

    } else {

        ערמת_פסולת.push(
            קלף
        );

    }


    פרסם(

        "קלף_שוחק",

        {

            קלף,

            גודליד:
                יד_נוכחית.length

        }

    );


    return קלף;

}


/* =========================================================
   Getters
========================================================= */

function קבליד() {

    return [
        ...יד_נוכחית
    ];

}


function קבלגודלחפיסתמשיכה() {

    return חפיסת_משיכה.length;

}


function קבלגודלערמתפסולת() {

    return ערמת_פסולת.length;

}


/* =========================================================
   Export
========================================================= */

export {

    אתחלמערכתקלפים,

    קבלחפיסתגיבור,

    התחלחפיסתקרב,

    משוךקלפים,

    שחקקלף,

    קבליד,

    קבלגודלחפיסתמשיכה,

    קבלגודלערמתפסולת

};
