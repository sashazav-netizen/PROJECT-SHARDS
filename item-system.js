/* =========================================================
   עזר: מזהה ייחודי למופע חפץ
========================================================= */

function מזההחדש() {

    return (

        "item-" +

        Date.now() +

        "-" +

        Math.floor(
            Math.random() * 100000
        )

    );

}


/* =========================================================
   קבלת רשימת חפצי השחקן (עם נתוני התבנית)
========================================================= */

function קבלחפציהשחקן() {

    const מצב =
        קבלמצב();


    if (
        !מצב ||
        !Array.isArray(מצב.חפצים)
    ) {

        return [];

    }


    return מצב.חפצים

        .map(

            מופע => {

                const תבנית =
                    נתוני_חפצים[
                        מופע.מפתח
                    ];


                if (
                    !תבנית
                ) {

                    return null;

                }


                return {

                    ...תבנית,

                    instanceId:
                        מופע.instanceId,

                    מוגבלמגיבור:
                        מופע.מוגבלמגיבור || null

                };

            }

        )

        .filter(Boolean);

}


/* =========================================================
   קבלת חפץ בודד לפי instanceId
========================================================= */

function קבלחפץ(
    instanceId
) {

    return (

        קבלחפציהשחקן().find(

            ח =>
                ח.instanceId === instanceId

        )

        ||
        null

    );

}


/* =========================================================
   הוספת חפץ לתיק
========================================================= */

function הוסףחפץ(
    מפתח
) {

    const תבנית =
        נתוני_חפצים[
            מפתח
        ];


    if (
        !תבנית
    ) {

        console.error(

            `[Item System] לא ניתן להוסיף חפץ לא קיים: ${מפתח}`

        );

        return null;

    }


    const מצב =
        קבלמצב();


    if (
        !מצב
    ) {

        return null;

    }


    if (
        !Array.isArray(מצב.חפצים)
    ) {

        מצב.חפצים = [];

    }


    const instanceId =
        מזההחדש();


    מצב.חפצים.push(

        {

            instanceId,

            מפתח,

            מוגבלמגיבור:
                null

        }

    );


    פרסם(

        "חפץ_נוסף",

        {

            instanceId,

            מפתח

        }

    );


    return instanceId;

}


/* =========================================================
   עזר: החלת/ביטול בונוסי חפץ על סטטי גיבור
========================================================= */

function החלבונוסים(
    גיבור,
    בונוסים
) {

    if (
        בונוסים.attack
    ) {

        גיבור.stats.attack +=
            בונוסים.attack;

    }


    if (
        בונוסים.defense
    ) {

        גיבור.stats.defense +=
            בונוסים.defense;

    }


    if (
        בונוסים.speed
    ) {

        גיבור.stats.speed +=
            בונוסים.speed;

    }


    if (
        בונוסים.hp
    ) {

        גיבור.stats.maxHp +=
            בונוסים.hp;

        גיבור.stats.hp +=
            בונוסים.hp;

    }

}


function בטלבונוסים(
    גיבור,
    בונוסים
) {

    if (
        בונוסים.attack
    ) {

        גיבור.stats.attack =

            Math.max(

                0,

                גיבור.stats.attack - בונוסים.attack

            );

    }


    if (
        בונוסים.defense
    ) {

        גיבור.stats.defense =

            Math.max(

                0,

                גיבור.stats.defense - בונוסים.defense

            );

    }


    if (
        בונוסים.speed
    ) {

        גיבור.stats.speed =

            Math.max(

                0,

                גיבור.stats.speed - בונוסים.speed

            );

    }


    if (
        בונוסים.hp
    ) {

        גיבור.stats.maxHp =

            Math.max(

                1,

                גיבור.stats.maxHp - בונוסים.hp

            );


        גיבור.stats.hp =

            Math.min(

                גיבור.stats.hp,

                גיבור.stats.maxHp

            );

    }

}


/* =========================================================
   הסרת ציוד ממשבצת
========================================================= */

function הסרציודגיבור(
    idגיבור,
    סוג
) {

    const גיבור =
        קבלגיבור(
            idגיבור
        );


    if (
        !גיבור ||
        !גיבור.equipment
    ) {

        return false;

    }


    const instanceIdקודם =
        גיבור.equipment[
            סוג
        ];


    if (
        !instanceIdקודם
    ) {

        return false;

    }


    const חפץקודם =
        קבלחפץ(
            instanceIdקודם
        );


    if (
        חפץקודם
    ) {

        בטלבונוסים(

            גיבור,

            חפץקודם.בונוסים || {}

        );

    }


    גיבור.equipment[
        סוג
    ] = null;


    const מצב =
        קבלמצב();


    if (
        מצב &&
        Array.isArray(מצב.חפצים)
    ) {

        const מופע =
            מצב.חפצים.find(

                ח =>
                    ח.instanceId === instanceIdקודם

            );


        if (
            מופע
        ) {

            מופע.מוגבלמגיבור =
                null;

        }

    }


    סנכרןלמצב();


    פרסם(

        "חפץ_הוסר",

        {

            idגיבור,

            סוג,

            instanceId:
                instanceIdקודם

        }

    );


    return true;

}


/* =========================================================
   ציוד חפץ על גיבור
========================================================= */

function ציידחפץ(
    idגיבור,
    instanceId
) {

    const גיבור =
        קבלגיבור(
            idגיבור
        );


    if (
        !גיבור ||
        !גיבור.equipment
    ) {

        return false;

    }


    const חפץ =
        קבלחפץ(
            instanceId
        );


    if (
        !חפץ
    ) {

        console.warn(

            `[Item System] חפץ לא נמצא: ${instanceId}`

        );

        return false;

    }


    if (
        חפץ.מוגבלמגיבור &&
        חפץ.מוגבלמגיבור !== idגיבור
    ) {

        console.warn(

            "[Item System] החפץ כבר מצויד על גיבור אחר."

        );

        return false;

    }


    const סוג =
        חפץ.סוג;


    /*
     * אם יש כבר משהו במשבצת הזו — מסירים אותו קודם
     * (מבטל את הבונוסים שלו לפני שמחילים את החדש).
     */

    if (
        גיבור.equipment[סוג]
        &&
        גיבור.equipment[סוג] !== instanceId
    ) {

        הסרציודגיבור(
            idגיבור,
            סוג
        );

    }


    /*
     * אם החפץ הזה כבר מצויד בדיוק על הגיבור הזה —
     * אין מה לעשות.
     */

    if (
        גיבור.equipment[סוג] === instanceId
    ) {

        return true;

    }


    החלבונוסים(

        גיבור,

        חפץ.בונוסים || {}

    );


    גיבור.equipment[
        סוג
    ] = instanceId;


    const מצב =
        קבלמצב();


    if (
        מצב &&
        Array.isArray(מצב.חפצים)
    ) {

        const מופע =
            מצב.חפצים.find(

                ח =>
                    ח.instanceId === instanceId

            );


        if (
            מופע
        ) {

            מופע.מוגבלמגיבור =
                idגיבור;

        }

    }


    סנכרןלמצב();


    פרסם(

        "חפץ_צויד",

        {

            idגיבור,

            סוג,

            instanceId

        }

    );


    return true;

}


/* =========================================================
   מכירת חפץ
========================================================= */

/**
 * מוכר חפץ תמורת כסף. חפץ מצויד לא ניתן למכירה —
 * צריך להסיר אותו קודם.
 *
 * המרה: מחיר יהלומים מומר לכסף ביחס 1:10 לצורך
 * חישוב תמורת המכירה (50% מהמחיר הכולל).
 */

function מכורחפץ(
    instanceId
) {

    const חפץ =
        קבלחפץ(
            instanceId
        );


    if (
        !חפץ
    ) {

        return false;

    }


    if (
        חפץ.מוגבלמגיבור
    ) {

        console.warn(

            "[Item System] לא ניתן למכור חפץ מצויד — יש להסיר אותו קודם."

        );

        return false;

    }


    const מחיר =
        חפץ.מחיר || {
            כסף: 0,
            יהלומים: 0
        };


    const ערךכולל =

        (מחיר.כסף || 0) +

        (מחיר.יהלומים || 0) * 10;


    const תמורה =

        Math.floor(
            ערךכולל * 0.5
        );


    const מצב =
        קבלמצב();


    if (
        מצב &&
        Array.isArray(מצב.חפצים)
    ) {

        מצב.חפצים =
            מצב.חפצים.filter(

                ח =>
                    ח.instanceId !== instanceId

            );

    }


    if (
        תמורה > 0
    ) {

        שנהמשאב(
            "כסף",
            תמורה
        );

    }


    פרסם(

        "חפץ_נמכר",

        {

            instanceId,

            תמורה

        }

    );


    return true;

}


