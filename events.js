const מאזינים = new Map();


/**
 * הרשמה לאירוע.
 */
function הירשם(שםאירוע, פונקציה) {

    if (
        typeof פונקציה !== "function"
    ) {

        console.error(
            "לא ניתן להירשם לאירוע ללא פונקציה."
        );

        return () => {};
    }


    if (!מאזינים.has(שםאירוע)) {

        מאזינים.set(
            שםאירוע,
            new Set()
        );

    }


    const רשימתמאזינים =
        מאזינים.get(שםאירוע);

    רשימתמאזינים.add(פונקציה);


    /**
     * מאפשר ביטול הרשמה.
     */
    return () => {

        רשימתמאזינים.delete(
            פונקציה
        );

    };
}


/**
 * הפעלת אירוע.
 */
function פרסם(שםאירוע, נתונים = {}) {

    const רשימתמאזינים =
        מאזינים.get(שםאירוע);

    if (!רשימתמאזינים) {

        return;

    }


    for (
        const פונקציה
        of רשימתמאזינים
    ) {

        try {

            פונקציה(נתונים);

        } catch (שגיאה) {

            console.error(
                `שגיאה באירוע: ${שםאירוע}`,
                שגיאה
            );

        }

    }

}


/**
 * הסרת כל המאזינים מאירוע.
 */
function נקהאירוע(שםאירוע) {

    מאזינים.delete(
        שםאירוע
    );

}


/**
 * ניקוי כל מערכת האירועים.
 */
function נקההכל() {

    מאזינים.clear();

}


export {

    הירשם,
    פרסם,
    נקהאירוע,
    נקההכל

};